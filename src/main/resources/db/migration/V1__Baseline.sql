-- Notifications have a subject (user) that does notif type (enum) to an target (content).
-- The recipient is the user that receives the notification.
CREATE TABLE notifications
(
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL ,
    subject_id BIGINT,
    target_content_id BIGINT,
    notification_type VARCHAR(255) NOT NULL,
    message VARCHAR(255),
    created_at TIMESTAMP with time zone NOT NULL,

    CONSTRAINT pk_notifications PRIMARY KEY (id),
    CONSTRAINT fk_subject_id FOREIGN KEY (subject_id) REFERENCES users (id),
    CONSTRAINT fk_target_content_id FOREIGN KEY (target_content_id) REFERENCES content (id) ON DELETE CASCADE
);

CREATE TABLE notifications_to_recipients
(
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL ,
    notification_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT pk_notifications_to_users PRIMARY KEY (id),
    CONSTRAINT fk_notification_id FOREIGN KEY (notification_id) REFERENCES notifications (id) ON DELETE CASCADE,
    CONSTRAINT fk_user_id FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uc_notifications_to_users UNIQUE (notification_id, user_id)
);

CREATE TABLE reports
(
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL ,
    author_id BIGINT NOT NULL,
    reason VARCHAR(255) NOT NULL,
    category VARCHAR(50) NOT NULL,
    created_at TIMESTAMP with time zone NOT NULL,
    reported_content_id BIGINT NOT NULL,
    resolver_id BIGINT,

    CONSTRAINT pk_reports PRIMARY KEY (id),
    CONSTRAINT fk_author_id FOREIGN KEY (author_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_reported_content_id FOREIGN KEY (reported_content_id) REFERENCES content (id) ON DELETE CASCADE,
    CONSTRAINT fk_resolver_id FOREIGN KEY (resolver_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE TABLE announcements
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    title VARCHAR(255) NOT NULL,
    body TEXT NOT NULL,
    author_id BIGINT NOT NULL,
    created_at TIMESTAMP with time zone NOT NULL,
    updated_at TIMESTAMP with time zone NOT NULL,

    CONSTRAINT pk_announcements PRIMARY KEY (id)
);




